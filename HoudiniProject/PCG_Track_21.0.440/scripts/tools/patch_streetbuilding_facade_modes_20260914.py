def apply(hou, save=False):
    assert not save, 'Persistence is owned by VerifyFull'
    a=hou.node('/obj/StreetBuilding_DEV')
    assert a is not None and a.type().name()=='pcgbike::StreetBuilding::1.0'
    marker='STREETBUILDING_FACADE_MODES_SIMPLIFIED_20260914'
    if marker in a.node('StreetBuildingCore/PARSE_GENERATION_RULES').evalParm('snippet'):
        assert all(a.node(k).evalParm('snippet')==v['after'] for k,v in EDITS.items())
        assert a.node('StreetBuildingCore/VISIBLE_SHELL_POLICY') is None
        return 'already-applied'
    original={k:a.node(k).evalParm('snippet') for k in EDITS}
    for key,value in original.items():
        assert hashlib.sha256(value.encode()).hexdigest()==EDITS[key]['sha256'], 'Live changed: '+key
    policy=a.node('StreetBuildingCore/VISIBLE_SHELL_POLICY')
    assert policy is not None and policy.input(0)==a.node('StreetBuildingCore/RESOLVE_FACADE_GRAMMAR')
    targets=[(c.outputNode(),c.inputIndex()) for c in policy.outputConnections()]
    assert {n.name() for n,i in targets}=={'BUILD_LOD0','BUILD_LOD1','BUILD_LOD2','BUILD_COLLISION','BUILD_METADATA'}
    group=a.parmTemplateGroup()
    rear=a.evalParm('rear_facade_mode')
    try:
        with hou.undos.group('Remove obsolete facade modes'):
            for key,value in EDITS.items():a.node(key).parm('snippet').set(value['after'])
            # Definition-owned inherited controls are finalized by the common
            # candidate/production promotion helper after cumulative validation.
            changed=a.parmTemplateGroup()
            if changed.find('side_facade_mode') is not None:changed.remove('side_facade_mode')
            a.setParmTemplateGroup(changed)
            a.parm('rear_facade_mode').set(2 if rear>0 else 0)
            for target,index in targets:target.setInput(index,policy.input(0))
            policy.destroy()
    except Exception:
        hou.undos.performUndo()
        for key,value in original.items():assert a.node(key).evalParm('snippet')==value
        raise
    return 'applied-without-saving'
